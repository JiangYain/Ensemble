/** 按夹具造出一张画布的会话：id 是 `<name>-<位置>`，创建先后就是位置；每次调用现造，不共用对象。 */
export function realSessions(canvas: RealCanvas): SessionSummary[] {
  return canvas.parents.map((parent, index) =>
    session(`${canvas.name}-${index}`, canvas.key, index + 1, parent >= 0 ? { parentSessionId: `${canvas.name}-${parent}` } : {}),
  );
}
